  <h2>What this portal records</h2>
  <p>Royal Indian Stones keeps a private staff record when you sign in, use an authenticator, or mark attendance.</p>
  <ul>
    <li>The time, your account, and the session identifier.</li>
    <li>The public IP address observed by the server, and whether it matches an office, factory, or warehouse range.</li>
    <li>A short description of the browser. A registered-device cookie may be stored so HR can approve or revoke that browser.</li>
    <li>Attendance only when you press clock in, clock out, or break. Signing in does not mark you present.</li>
  </ul>
  <p>An approved network or device is a signal. It does not prove a person is physically on site. Remote and field work is labelled separately. The browser cannot read a computer’s MAC address.</p>
  <p>Employer and HR can review these records. Login verification events are kept for {{ config('portal.retention.access_events_months') }} months. Attendance, payslips, and identity files follow the retention periods in the staff setup notes and are not published on the website.</p>
</div>
